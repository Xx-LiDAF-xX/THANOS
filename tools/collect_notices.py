"""Collect restored NuGet license metadata and bundled notices. Run after dependency updates."""
import json
import re
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "licenses"
DESTINATION.mkdir(exist_ok=True)

# Source licenses supply copyright notices when a package only declares an SPDX expression.
SOURCE_LICENSES = {
    "Avalonia": "https://raw.githubusercontent.com/AvaloniaUI/Avalonia/11.3.14/licence.md",
    "Microsoft": "https://raw.githubusercontent.com/dotnet/efcore/v10.0.9/LICENSE.txt",
    "SQLitePCLRaw": "https://raw.githubusercontent.com/ericsink/SQLitePCL.raw/v2.1.11/LICENSE.TXT",
    "MicroCom": "https://raw.githubusercontent.com/kekekeks/MicroCom/master/LICENSE",
    "Tmds": "https://raw.githubusercontent.com/tmds/Tmds.DBus/main/COPYING",
    "xunit": "https://raw.githubusercontent.com/xunit/xunit/main/LICENSE",
}


def metadata(path):
    tree = ET.parse(path)
    element = next(e for e in tree.getroot().iter() if e.tag.split("}")[-1] == "metadata")
    return {child.tag.split("}")[-1]: child for child in element}


packages = {}
for assets_path in sorted(ROOT.glob("**/obj/project.assets.json")):
    assets = json.loads(assets_path.read_text(encoding="utf-8"))
    for name, entry in assets["libraries"].items():
        if entry["type"] != "package":
            continue
        for folder in assets["packageFolders"]:
            path = Path(folder) / entry["path"]
            if path.is_dir():
                packages[name] = path
                break

rows = []
for name, path in sorted(packages.items(), key=lambda item: item[0].lower()):
    package_name = name.split("/")[0]
    nuspec = next(path.glob("*.nuspec"))
    spec = metadata(nuspec)
    license_node = spec.get("license")
    declared_license = license_node.text if license_node is not None else spec.get("licenseUrl", ET.Element("empty")).text
    declared_license = declared_license or "UNKNOWN"
    notices = []
    for file in sorted(path.iterdir()):
        if file.is_file() and re.search(r"license|licence|notice|copying", file.name, re.I) and file.suffix.lower() not in (".nupkg", ".sha512"):
            filename = re.sub(r"[^a-zA-Z0-9._-]", "_", name + "-" + file.name)
            (DESTINATION / filename).write_bytes(file.read_bytes())
            notices.append(filename)
    if not notices:
        for prefix, url in SOURCE_LICENSES.items():
            if package_name.startswith(prefix):
                filename = prefix + "-source-LICENSE.txt"
                target = DESTINATION / filename
                if not target.exists():
                    with urllib.request.urlopen(url, timeout=30) as response:
                        target.write_bytes(response.read())
                notices.append(filename)
                break
    if not notices:
        raise SystemExit(f"Missing copyright/license notice for {name}; review before distribution.")
    if license_node is not None and license_node.get("type") == "expression" and declared_license not in ("MIT", "Apache-2.0", "BSD-3-Clause", "BSD-2-Clause"):
        raise SystemExit(f"Review license compatibility: {name}: {declared_license}")
    rows.append({"package": name, "declaredLicense": declared_license, "notices": notices})

(DESTINATION / "nuget-inventory.json").write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8", newline="\n")
header = """THANOS THIRD-PARTY NOTICES

THANOS source is GPL-3.0-or-later. Dependencies retain their own licenses.
This inventory includes runtime and contributor/test packages from the restored graph.
MIT, Apache-2.0 and BSD licenses in this graph permit combination with GPLv3.
SQLitePCLRaw's native SQLite library is public domain; ANGLE carries BSD-style terms.
Native component terms (including SkiaSharp third-party notices) are retained below
in licenses/. Review native source/license requirements before shipping a release.
These files must accompany distributed application packages. A self-contained .NET
release must additionally include runtime notices; Phase 1 packages use an external runtime.

The precise versions/content hashes are pinned in packages.lock.json. This inventory
is generated by tools/collect_notices.py from NuGet manifests and supplied notices.
Python schema tooling is a contributor dependency (jsonschema and its dependencies
use MIT); no Python components are included in application packages.

"""
lines = [header]
for row in rows:
    lines.append(f"{row['package']} | {row['declaredLicense']} | " + ", ".join("licenses/" + name for name in row["notices"]))
(ROOT / "THIRD-PARTY-NOTICES").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"Collected notices for {len(rows)} packages.")
